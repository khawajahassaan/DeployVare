using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using API.DTOs.Responses;

namespace API.Utilities;

/// <summary>
/// Frontend runtime settings: validation, storage format and generation of the config.js the frontend loads
/// before its bundle (window.__APP_CONFIG__).
/// </summary>
public static class FrontendRuntimeConfig
{
    public const int MaxSettings = 50;
    public const int MaxValueLength = 2000;

    private static readonly Regex KeyPattern = new(@"^VITE_[A-Z0-9_]{1,100}$", RegexOptions.Compiled);
    private static readonly JsonSerializerOptions IndentedJson = new() { WriteIndented = true };

    /// <summary>Keys offered when a server has no settings yet.</summary>
    public static readonly IReadOnlyList<string> StandardKeys = new[]
    {
        "VITE_AD_REDIRECT_URL",
        "VITE_ADMIN_CENTER_URL",
        "VITE_API_URL",
        "VITE_DB_NAME",
        "VITE_SOCKET_URL",
        "VITE_URL"
    };

    /// <summary>All keys the frontend reads at runtime (RUNTIME_ENV_KEYS in the frontend's vite.config.mjs).</summary>
    public static readonly IReadOnlyList<string> SuggestedKeys = StandardKeys.Concat(new[]
    {
        "VITE_AD_AUTH_URL",
        "VITE_AD_CLIENT_ID",
        "VITE_AD_TENANT_ID",
        "VITE_COMPANY_LOGO",
        "VITE_AI_URL",
        "VITE_YANI_BASE_URL",
        "VITE_YANI_BASE_ONPREM_URL",
        "VITE_YANI_SUBSCRIPTION_KEY",
        "VITE_YANI_SUBSCRIPTION_ONPREM_KEY"
    }).ToList();

    /// <summary>
    /// Trims and validates settings. Entries with an empty value are dropped so the frontend falls back to
    /// the value built into the artifact.
    /// </summary>
    public static List<RuntimeSettingDto> Normalize(IEnumerable<RuntimeSettingDto>? settings)
    {
        var result = new List<RuntimeSettingDto>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var setting in settings ?? Enumerable.Empty<RuntimeSettingDto>())
        {
            var key = setting.Key?.Trim().ToUpperInvariant() ?? string.Empty;
            var value = setting.Value?.Trim() ?? string.Empty;

            if (key.Length == 0 && value.Length == 0)
                continue;

            if (!KeyPattern.IsMatch(key))
                throw new InvalidOperationException(
                    $"'{setting.Key}' is not a valid setting name. Names start with VITE_ and use only letters, digits and underscores.");

            if (value.Length == 0)
                continue;

            if (value.Length > MaxValueLength || value.Any(char.IsControl))
                throw new InvalidOperationException($"The value of {key} is too long or contains invalid characters.");

            if (!seen.Add(key))
                throw new InvalidOperationException($"{key} is listed more than once.");

            result.Add(new RuntimeSettingDto { Key = key, Value = value });
        }

        if (result.Count > MaxSettings)
            throw new InvalidOperationException($"A server can have at most {MaxSettings} runtime settings.");

        return result;
    }

    public static List<RuntimeSettingDto> Parse(string? json)
    {
        if (string.IsNullOrWhiteSpace(json))
            return new List<RuntimeSettingDto>();

        try
        {
            return JsonSerializer.Deserialize<List<RuntimeSettingDto>>(json) ?? new List<RuntimeSettingDto>();
        }
        catch (JsonException)
        {
            return new List<RuntimeSettingDto>();
        }
    }

    public static string? Serialize(IReadOnlyCollection<RuntimeSettingDto> settings) =>
        settings.Count == 0 ? null : JsonSerializer.Serialize(settings);

    /// <summary>
    /// Builds config.js. Values are JSON-encoded with the default encoder, which escapes quotes, &lt; and &gt;,
    /// so a value can never break out of the script.
    /// </summary>
    public static string BuildConfigJs(string serverName, IReadOnlyList<RuntimeSettingDto> settings, DateTime generatedAtUtc)
    {
        var config = new JsonObject();
        foreach (var setting in settings)
            config[setting.Key] = setting.Value;

        var safeServerName = (serverName ?? string.Empty).Replace('\r', ' ').Replace('\n', ' ');

        return $"// Generated by DeployVare for server \"{safeServerName}\" at {generatedAtUtc:yyyy-MM-dd HH:mm:ss} UTC.\n"
            + "// Managed in DeployVare (Server Setup > Frontend Runtime Settings); manual changes are overwritten on the next deploy.\n"
            + $"window.__APP_CONFIG__ = {config.ToJsonString(IndentedJson)};\n";
    }
}

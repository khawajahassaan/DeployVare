using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace API.Utilities;

/// <summary>
/// Makes sure a backend package carries an appsettings.json. Build pipelines often leave it out of the artifact
/// (production settings live on the server), which left manual packages with no file to edit. When the build has
/// one it is kept exactly as built; otherwise a template is written from the build's own appsettings.*.json (so
/// the keys match the application) or a minimal layout, with ConnectionStrings set to an obvious value to edit.
/// </summary>
public static class AppSettingsTemplate
{
    public const string FileName = "appsettings.json";
    public const string DefaultConnectionName = "DefaultConnection";

    /// <summary>Environment files the template is based on, most production-like first.</summary>
    private static readonly string[] BaseFiles =
    {
        "appsettings.Production.json",
        "appsettings.Staging.json",
        "appsettings.Development.json"
    };

    private static readonly JsonDocumentOptions ReadOptions = new()
    {
        CommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true
    };

    private static readonly JsonSerializerOptions WriteOptions = new() { WriteIndented = true };

    public sealed record Result(bool Generated, string Path, string? BasedOn);

    /// <summary>
    /// Windows/IIS connection string: Windows authentication (the app pool identity is granted access by
    /// Deploy.ps1), or a SQL login when the database is on another machine.
    /// </summary>
    public static string WindowsConnectionString(string? dataSource, string? databaseName, bool sqlLogin) =>
        sqlLogin
            ? $"Server={Or(dataSource, "<SQL_SERVER>")};Database={Or(databaseName, "<DATABASE_NAME>")};User Id=<SQL_LOGIN>;Password=<SQL_PASSWORD>;TrustServerCertificate=True;MultipleActiveResultSets=True"
            : $"Server={Or(dataSource, @".\SQLEXPRESS")};Database={Or(databaseName, "<DATABASE_NAME>")};Integrated Security=True;TrustServerCertificate=True;MultipleActiveResultSets=True";

    /// <summary>Linux connection string: always a SQL login (Windows authentication is not available on Linux).</summary>
    public static string LinuxConnectionString(string? server, string? databaseName, string? login) =>
        $"Server={Or(server, "<SQL_SERVER>")},1433;Database={Or(databaseName, "<DATABASE_NAME>")};User Id={Or(login, "<SQL_LOGIN>")};Password=<SQL_PASSWORD>;TrustServerCertificate=True;MultipleActiveResultSets=True";

    /// <summary>
    /// Writes appsettings.json into <paramref name="appDirectory"/> when it is missing. An existing file is never
    /// changed. Every connection string of the template is set to <paramref name="connectionString"/>.
    /// </summary>
    public static Result Ensure(string appDirectory, string connectionString)
    {
        var target = System.IO.Path.Combine(appDirectory, FileName);
        if (File.Exists(target))
            return new Result(false, target, null);

        string? basedOn = null;
        JsonObject? root = null;
        foreach (var name in BaseFiles)
        {
            var candidate = System.IO.Path.Combine(appDirectory, name);
            if (!File.Exists(candidate)) continue;
            root = TryParseObject(File.ReadAllText(candidate));
            if (root == null) continue;
            basedOn = name;
            break;
        }

        root ??= new JsonObject
        {
            ["Logging"] = new JsonObject
            {
                ["LogLevel"] = new JsonObject
                {
                    ["Default"] = "Information",
                    ["Microsoft.AspNetCore"] = "Warning"
                }
            },
            ["AllowedHosts"] = "*"
        };

        // ConnectionStrings first, so it is the first thing seen when the file is opened
        var connections = root["ConnectionStrings"] as JsonObject;
        var names = connections?.Select(p => p.Key).ToList() ?? new List<string>();
        if (names.Count == 0) names.Add(DefaultConnectionName);
        root.Remove("ConnectionStrings");

        var ordered = new JsonObject();
        var templateConnections = new JsonObject();
        foreach (var name in names) templateConnections[name] = connectionString;
        ordered["ConnectionStrings"] = templateConnections;
        foreach (var (key, value) in root.ToList())
        {
            root.Remove(key);
            ordered[key] = value;
        }

        var header = new StringBuilder()
            .AppendLine("// Generated by DeployVare: this build has no appsettings.json.")
            .AppendLine(basedOn == null
                ? "// Minimal template. Add any other settings the application needs."
                : $"// Based on {basedOn} from the build, with the connection strings replaced.")
            .AppendLine("// Edit ConnectionStrings (replace every <...> value) before starting the application.")
            .AppendLine("// When the server already has an appsettings.json, the deployment keeps the server's file.")
            .ToString();

        File.WriteAllText(target, header + ordered.ToJsonString(WriteOptions) + Environment.NewLine, new UTF8Encoding(false));
        return new Result(true, target, basedOn);
    }

    private static JsonObject? TryParseObject(string json)
    {
        try
        {
            return JsonNode.Parse(json, documentOptions: ReadOptions) as JsonObject;
        }
        catch (JsonException)
        {
            return null;
        }
    }

    private static string Or(string? value, string fallback) =>
        string.IsNullOrWhiteSpace(value) ? fallback : value.Trim();
}

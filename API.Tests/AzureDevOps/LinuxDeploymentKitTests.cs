namespace API.Tests.AzureDevOps;

public class LinuxDeploymentKitTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "DeployVareTests", Guid.NewGuid().ToString("N"));

    public LinuxDeploymentKitTests() => Directory.CreateDirectory(_root);

    public void Dispose()
    {
        if (Directory.Exists(_root)) Directory.Delete(_root, true);
    }

    private string Folder(string name)
    {
        var path = Path.Combine(_root, name);
        Directory.CreateDirectory(path);
        return path;
    }

    private static JsonObject ReadJsonWithComments(string path) =>
        (JsonNode.Parse(File.ReadAllText(path), documentOptions: new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip }) as JsonObject)!;

    // ---- appsettings.json template ----

    [Fact]
    public void AppSettings_ExistingFileIsNeverChanged()
    {
        var app = Folder("app");
        File.WriteAllText(Path.Combine(app, "appsettings.json"), "{ \"ConnectionStrings\": { \"Db\": \"real\" } }");

        var result = AppSettingsTemplate.Ensure(app, "template");

        Assert.False(result.Generated);
        Assert.Equal("{ \"ConnectionStrings\": { \"Db\": \"real\" } }", File.ReadAllText(Path.Combine(app, "appsettings.json")));
    }

    [Fact]
    public void AppSettings_MissingFile_IsBuiltFromProductionSettingsWithConnectionNamesKept()
    {
        var app = Folder("app");
        File.WriteAllText(Path.Combine(app, "appsettings.Production.json"), """
            {
              // comments and trailing commas are allowed in .NET settings files
              "Redis": { "Host": "localhost:6379" },
              "ConnectionStrings": { "AuditVareDb": "Server=prod;Password=secret", "Hangfire": "x" },
            }
            """);
        File.WriteAllText(Path.Combine(app, "appsettings.Development.json"), "{ \"Dev\": true }");

        var result = AppSettingsTemplate.Ensure(app, "Server=<SQL_SERVER>;Password=<SQL_PASSWORD>");

        Assert.True(result.Generated);
        Assert.Equal("appsettings.Production.json", result.BasedOn);
        var text = File.ReadAllText(result.Path);
        Assert.StartsWith("// Generated by DeployVare", text);
        Assert.DoesNotContain("secret", text);

        var json = ReadJsonWithComments(result.Path);
        Assert.Equal("ConnectionStrings", json.First().Key);
        Assert.Equal("Server=<SQL_SERVER>;Password=<SQL_PASSWORD>", (string)json["ConnectionStrings"]!["AuditVareDb"]!);
        Assert.Equal("Server=<SQL_SERVER>;Password=<SQL_PASSWORD>", (string)json["ConnectionStrings"]!["Hangfire"]!);
        Assert.Equal("localhost:6379", (string)json["Redis"]!["Host"]!);
        Assert.Null(json["Dev"]);
    }

    [Fact]
    public void AppSettings_NoSettingsInBuild_WritesMinimalTemplateWithDefaultConnection()
    {
        var app = Folder("app");

        var result = AppSettingsTemplate.Ensure(app, AppSettingsTemplate.LinuxConnectionString("10.0.0.5", "AuditVare", null));

        Assert.True(result.Generated);
        Assert.Null(result.BasedOn);
        var json = ReadJsonWithComments(result.Path);
        Assert.Equal("Server=10.0.0.5,1433;Database=AuditVare;User Id=<SQL_LOGIN>;Password=<SQL_PASSWORD>;TrustServerCertificate=True;MultipleActiveResultSets=True",
            (string)json["ConnectionStrings"]!["DefaultConnection"]!);
        Assert.NotNull(json["Logging"]);
    }

    [Fact]
    public void AppSettings_WindowsTemplate_UsesIntegratedSecurityUnlessTheDatabaseIsElsewhere()
    {
        Assert.Contains("Integrated Security=True", AppSettingsTemplate.WindowsConnectionString(@".\SQLEXPRESS", "AuditVare", sqlLogin: false));
        var remote = AppSettingsTemplate.WindowsConnectionString("db01", "AuditVare", sqlLogin: true);
        Assert.Contains("User Id=<SQL_LOGIN>", remote);
        Assert.DoesNotContain("Integrated Security", remote);
    }

    // ---- Linux artifact choice ----

    private static AzureBuildArtifactDto Artifact(string name, bool downloadable = true) =>
        new() { Name = name, ResourceType = "Container", IsDownloadable = downloadable };

    [Fact]
    public void Artifact_PrefersLinuxArtifactNamedAfterTheConfiguredOne()
    {
        var choice = LinuxBuildInspector.SelectArtifact(
            new[] { Artifact("drop"), Artifact("tools-linux"), Artifact("drop-linux-x64"), Artifact("sqlscripts") },
            "drop", null, ServerType.Api);

        Assert.Equal("drop-linux-x64", choice.Name);
        Assert.True(choice.IsLinuxSpecific);
        Assert.Null(choice.Note);
    }

    [Fact]
    public void Artifact_WithoutLinuxArtifact_FallsBackToConfiguredWithNote()
    {
        var choice = LinuxBuildInspector.SelectArtifact(new[] { Artifact("drop"), Artifact("sqlscripts") }, "drop", null, ServerType.Api);

        Assert.Equal("drop", choice.Name);
        Assert.False(choice.IsLinuxSpecific);
        Assert.Contains("framework-dependent", choice.Note);
    }

    [Fact]
    public void Artifact_RequestedNameMustExist()
    {
        Assert.Throws<AzureDevOpsException>(() =>
            LinuxBuildInspector.SelectArtifact(new[] { Artifact("drop") }, "drop", "drop-linux", ServerType.Api));
    }

    // ---- Backend entry point ----

    private static void RuntimeConfig(string folder, string stem, string options) =>
        File.WriteAllText(Path.Combine(folder, $"{stem}.runtimeconfig.json"), $"{{ \"runtimeOptions\": {options} }}");

    [Fact]
    public void Entry_FrameworkDependentBuild_RunsTheAspNetCoreDllWithDotnet()
    {
        var app = Folder("fdd");
        File.WriteAllText(Path.Combine(app, "AuditVare.dll"), "");
        File.WriteAllText(Path.Combine(app, "DbMigrator.dll"), "");
        RuntimeConfig(app, "AuditVare", "{ \"frameworks\": [ { \"name\": \"Microsoft.NETCore.App\", \"version\": \"10.0.0\" }, { \"name\": \"Microsoft.AspNetCore.App\", \"version\": \"10.0.0\" } ] }");
        RuntimeConfig(app, "DbMigrator", "{ \"framework\": { \"name\": \"Microsoft.NETCore.App\", \"version\": \"10.0.0\" } }");

        var entry = LinuxBuildInspector.FindBackendEntry(app);

        Assert.Equal("AuditVare.dll", entry.EntryFile);
        Assert.False(entry.SelfContained);
        Assert.Equal(10, entry.DotNetMajor);
    }

    [Fact]
    public void Entry_SelfContainedLinuxBuild_RunsTheNativeBinary()
    {
        var app = Folder("scd");
        File.WriteAllText(Path.Combine(app, "AuditVare.dll"), "");
        File.WriteAllText(Path.Combine(app, "AuditVare"), "ELF");
        RuntimeConfig(app, "AuditVare", "{ \"includedFrameworks\": [ { \"name\": \"Microsoft.AspNetCore.App\", \"version\": \"9.0.4\" } ] }");

        var entry = LinuxBuildInspector.FindBackendEntry(app);

        Assert.Equal("AuditVare", entry.EntryFile);
        Assert.True(entry.SelfContained);
        Assert.Equal(9, entry.DotNetMajor);
    }

    [Fact]
    public void Entry_SelfContainedWindowsBuild_IsRejected()
    {
        var app = Folder("win");
        File.WriteAllText(Path.Combine(app, "AuditVare.dll"), "");
        File.WriteAllText(Path.Combine(app, "AuditVare.exe"), "MZ");
        RuntimeConfig(app, "AuditVare", "{ \"includedFrameworks\": [ { \"name\": \"Microsoft.AspNetCore.App\", \"version\": \"10.0.0\" } ] }");

        var ex = Assert.Throws<AzureDevOpsException>(() => LinuxBuildInspector.FindBackendEntry(app));
        Assert.Contains("win-x64", ex.Message);
    }

    // ---- Kit files ----

    [Fact]
    public void DbMigratorRuntimeConfig_IsAddedWhenThePublishLacksIt()
    {
        var app = Folder("migrator");
        File.WriteAllText(Path.Combine(app, "AuditVare.dll"), "");
        File.WriteAllText(Path.Combine(app, "DbMigrator.dll"), "");
        RuntimeConfig(app, "AuditVare", "{ \"frameworks\": [ { \"name\": \"Microsoft.AspNetCore.App\", \"version\": \"10.0.1\" } ] }");

        LinuxKitBuilder.EnsureDbMigratorRuntimeConfig(app, app);

        var json = JsonNode.Parse(File.ReadAllText(Path.Combine(app, "DbMigrator.runtimeconfig.json")))!;
        Assert.Equal("Microsoft.NETCore.App", (string)json["runtimeOptions"]!["framework"]!["name"]!);
        Assert.Equal("net10.0", (string)json["runtimeOptions"]!["tfm"]!);
    }

    [Fact]
    public void TarGz_HasOneRootFolder_ExecutableDeployScript_AndCamelCaseConfig()
    {
        var kit = Folder("kit");
        Directory.CreateDirectory(Path.Combine(kit, "app"));
        File.WriteAllText(Path.Combine(kit, "app", "AuditVare"), "ELF");
        File.WriteAllText(Path.Combine(kit, "app", "appsettings.json"), "{}");
        LinuxKitBuilder.WriteKitFiles(kit, new LinuxDeployConfig { KitType = "Api", SiteName = "auditvare-api", AppEntry = "AuditVare" }, "# readme");

        var tarPath = Path.Combine(_root, "AuditVare_linux-api-1.0.tar.gz");
        LinuxKitBuilder.CreateTarGz(kit, tarPath, new[] { "app/AuditVare" });

        var entries = new Dictionary<string, UnixFileMode>();
        using (var gzip = new GZipStream(File.OpenRead(tarPath), CompressionMode.Decompress))
        using (var reader = new TarReader(gzip))
        {
            while (reader.GetNextEntry() is { } entry)
                entries[entry.Name] = entry.Mode;
        }

        Assert.All(entries.Keys, name => Assert.StartsWith("AuditVare_linux-api-1.0/", name));
        Assert.True(entries["AuditVare_linux-api-1.0/Deploy.sh"].HasFlag(UnixFileMode.UserExecute));
        Assert.True(entries["AuditVare_linux-api-1.0/app/AuditVare"].HasFlag(UnixFileMode.UserExecute));
        Assert.False(entries["AuditVare_linux-api-1.0/app/appsettings.json"].HasFlag(UnixFileMode.UserExecute));

        var config = File.ReadAllText(Path.Combine(kit, LinuxKitBuilder.ConfigName));
        Assert.Contains("\"kitType\": \"Api\"", config);
        Assert.DoesNotContain("\r", File.ReadAllText(Path.Combine(kit, LinuxKitBuilder.DeployScriptName)));
    }

    [Theory]
    [InlineData("AuditVare", "auditvare")]
    [InlineData("Audit Vare (Web) ", "audit-vare-web")]
    [InlineData("!!!", "app")]
    public void Slug_IsSafeForFoldersServicesAndSiteFiles(string name, string expected) =>
        Assert.Equal(expected, LinuxKitBuilder.Slug(name));
}
